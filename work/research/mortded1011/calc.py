# 주담대 이자 소득공제 계산 (소득세법 제52조 제5·6항, 시행령 제112조)
# 가정: 대출 3억원, 금리 연 4.66%(한국은행 2026년 8월 예금은행 주담대 신규취급 평균), 30년
import sys; sys.stdout.reconfigure(encoding='utf-8')
P=300_000_000; r=0.0466/12; n=360
pay=P*r/(1-(1+r)**-n)
bal=P; yi=0
for m in range(12):
    i=bal*r; yi+=i; bal-=pay-i
print(f'원리금균등 월 상환 {pay:,.0f}원, 첫해 이자 {yi:,.0f}원, 첫해 원금 상환 {12*pay-yi:,.0f}원')
io=P*0.0466
print(f'거치(이자만) 첫해 이자 {io:,.0f}원')
# 비거치 최소 상환: 차입금 70%/상환연수 x 월수/12
print(f'비거치 요건 최소 연 상환 {P*0.7/30:,.0f}원')
lim={'고정+비거치(15년↑)':20_000_000,'고정 또는 비거치(15년↑)':18_000_000,'그 외 15년↑':8_000_000,'10년↑ 고정 또는 비거치':6_000_000}
for k,v in lim.items():
    for nm,inte in [('원리금균등',yi),('거치',io)]:
        d=min(inte,v)
        print(f'{k:20s} {nm}: 공제 {d:,.0f} → 세율15% {d*0.165:,.0f} / 24% {d*0.264:,.0f}')
# 연말 2주택: 공제 0
d=min(yi,20_000_000)
print(f'연말 2주택이면 잃는 환급: 15% {d*0.165:,.0f} / 24% {d*0.264:,.0f}')
# 비교(본문 표): 같은 3억·4.66%·30년, 첫 3년 이자만 내는 거치 → 첫해 이자 13,980,000원
print('--- 본문 표: 거치 3년, 첫해 이자', f'{io:,.0f}')
for nm,lim_ in [('5년 주기형(고정금리로 침)·15년 이상',18_000_000),('변동금리·15년 이상',8_000_000),('10년 이상 15년 미만·고정',6_000_000)]:
    d=min(io,lim_); print(f'{nm}: 한도 {lim_:,} 공제 {d:,.0f} 환급15% {d*0.165:,.0f} 24% {d*0.264:,.0f}')
print(f'주기형-변동 차이 {(min(io,18e6)-8e6):,.0f} → {(min(io,18e6)-8e6)*0.165:,.0f} / {(min(io,18e6)-8e6)*0.264:,.0f}')
