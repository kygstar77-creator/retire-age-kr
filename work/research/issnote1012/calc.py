# 발행어음 vs 은행 예금, 세후 이자 (단리·만기 일시 지급, 이자소득세 14% + 지방소득세 1.4%, 10원 미만 버림)
def net(p, r, m):
    g = int(round(p * r * m / 1200, 6))
    t1 = g * 14 // 100 // 10 * 10
    t2 = t1 // 10 // 10 * 10
    return g, t1 + t2, g - t1 - t2
P = 50_000_000
rows = [('한투 특판 신규자금 1년', 5.0, 12), ('한투 특판 기존고객 1년', 4.4, 12), ('삼성 특판 1년', 4.3, 12),
        ('삼성 일반 1년물', 3.95, 12), ('SC제일 e-그린세이브 최고(우대 포함)', 4.05, 12), ('SC제일 기본', 3.85, 12),
        ('농협 NH올원e예금 기본', 3.65, 12), ('우리 WON플러스 1년', 3.6, 12), ('국민 KB Star 최고', 3.5, 12), ('국민 KB Star 기본', 2.4, 12),
        ('한투 특판 신규 6개월', 4.7, 6), ('한투 특판 기존 6개월', 4.1, 6)]
out = {}
for n, r, m in rows:
    g, t, nt = net(P, r, m); out[n] = nt
    print(f'{n} {r}% {m}개월: 세전 {g:,} 세금 {t:,} 세후 {nt:,}')
print('키움 100만원 3개월 5.8%:', net(1_000_000, 5.8, 3))
print('한투신규-농협기본', out['한투 특판 신규자금 1년'] - out['농협 NH올원e예금 기본'])
print('한투신규-국민최고', out['한투 특판 신규자금 1년'] - out['국민 KB Star 최고'])
print('한투신규-SC최고', out['한투 특판 신규자금 1년'] - out['SC제일 e-그린세이브 최고(우대 포함)'])
print('한투신규-한투기존', out['한투 특판 신규자금 1년'] - out['한투 특판 기존고객 1년'])
print('삼성특판-삼성일반', out['삼성 특판 1년'] - out['삼성 일반 1년물'])
# 중도 인출: 6개월 보유, 고시 5.0%의 20%·70%
for k in (20, 70):
    print(f'6개월 뒤 인출 {k}%:', net(P, 5.0 * k / 100, 6))
print('키움 1억 넣었다 치면 3개월 세후(한도 넘어 불가, 비교용)', net(100_000_000, 5.8, 3))
