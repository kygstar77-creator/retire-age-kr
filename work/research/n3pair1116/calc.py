#  그대로: 건강 7.19%(2027 동결, 9/8 건정심 — 2차 두 곳) · 고용 0.9%(2027 인상은 정부안 단계, 확정 원문 없음 → 안 넣음) · 간이세액표(2026.2.27 판)
# 1인·식대 비과세 월 20만·자녀 0·간이세액 100% — ep/N-3/calc_out.txt §A와 같은 가정. 2026 칸은 §A 값을 다시 만들어 맞는지 본다.
A = {3000:(109250,82680,10860,2244440),4000:(148810,112640,14800,2935813),5000:(188380,142600,18730,3571586),
     6000:(228000,172560,22670,4195410),7000:(267560,202510,26600,4821313),8000:(307130,232470,30540,5367086),10000:(313020,292390,38420,6530923)}
CAP = 6590000  # 연금 기준소득월액 상한 2026.7~2027.6(2027.7 다시 정함)
f10 = lambda x: int(x)//10*10
for y,(p,h,c,net) in A.items():
    g = int(y*10000/12); base = min((g-200000)//1000*1000, CAP)
    p26, p27 = f10(base*0.0475), f10(base*0.05)
    h26 = f10((g-200000)*0.03595); c26 = f10(h26*0.1314); c27 = f10(h26*0.1390)
    assert (p26,h26,c26)==(p,h,c), (y,p26,h26,c26)
    d = (p27-p26)+(c27-c26)
    print(f"연봉 {y:,}만 | 연금 {p26:,}→{p27:,} | 요양 {c26:,}→{c27:,} | 더 떼는 돈 월 {d:,} (연 {d*12:,}) | 통장 2026 {net:,} → 2027 {net-d:,}")
