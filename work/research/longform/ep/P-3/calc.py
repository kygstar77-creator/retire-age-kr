# P-3 계산 — 피부양자 탈락 전·후 매달 건보료(소득분만). 원문: 시행령 제44조①(보험료율 1만분의 719, 2026-10-01판)
# 시행규칙 제44조②2호·③(지역가입자 연금·근로소득 100분의 50 반영, 2026-09-28판), 별표 1의2 제1호(합산 연 2천만원 이하)
# 시행령 부칙(대통령령 제32293호 관련) 탈락자 경감: 2022.9~2024.10 전액, 2024.11~2026.8 100분의 50 → 2026년 9월분부터 경감 없음
# 재산분·장기요양보험료·하한액은 넣지 않는다(재산 0 가정, 장기요양 요율은 확인 안 함).
RATE = 0.0719
def jiyeok_income_part(annual_pension, other_full=0):
    monthly = (annual_pension * 0.5 + other_full) / 12
    return round(monthly * RATE)
print('월 연금(만원) | 연 합계 | 피부양자 | 월 건보료(소득분) | 10년 합(만원)')
for m in [150, 160, 166, 167, 170, 180, 200, 250]:
    a = m * 12 * 10000
    ok = a <= 20_000_000
    fee = 0 if ok else jiyeok_income_part(a)
    print(f'{m:>4} | {a/1e4:>6,.0f}만 | {"유지" if ok else "탈락"} | {fee:>8,}원 | {fee*120/1e4:,.0f}')
# 경계: 연 2천만원 = 월 1,666,666원
print('경계 월액', 20_000_000/12)
# 경감 끝난 효과: 월 170만원 연금, 2026.8월분(50% 경감) vs 9월분
f = jiyeok_income_part(170*12*10000); print('170만: 8월분', f//2, '→ 9월분', f)
# 이자·배당이 섞인 경우: 연금 월 150(연 1,800) + 이자·배당 300만 = 2,100 → 탈락, 소득분
a, o = 1800*10000, 300*10000
print('연금1800+이자300 →', jiyeok_income_part(a, o), '원/월')
