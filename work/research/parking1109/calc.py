tiers = {
 "다올 Fi 쌈짓돈Ⅲ": [(1_000_000,5.0),(50_000_000,3.5),(None,2.5)],
 "우리금융 첫번째저축예금": [(50_000_000,3.5),(None,1.1)],
 "키움 더 키움 플러스 파킹통장": [(200_000_000,3.3),(None,2.0)],
 "예가람 The프리미엄 멤버십": [(None,3.2)],
 "HB 하루플러스통장": [(1_000_000,5.0),(10_000_000,4.0),(50_000_000,3.0),(None,2.5)],
 "IBK저축 e-파킹통장": [(300_000_000,3.2),(1_000_000_000,1.5),(None,0.1)],
 "고려 보고파플러스": [(None,3.1)],
 "DB행복파킹통장(첫거래 최고)": [(3_000_000,5.0),(30_000_000,3.0),(None,2.5)],
 "모아 e-모아파킹통장": [(1_000_000,4.0),(10_000_000,3.5),(None,1.0)],
 "카카오뱅크 세이프박스": [(100_000_000,1.8)],
 "저축은행 기본금리 중앙값": [(None,0.275)],
}
def yearly(amt,t):
    s=0;prev=0
    for cap,r in t:
        top=amt if cap is None else min(amt,cap)
        if top>prev: s+=(top-prev)*r/100; prev=top
        if cap is not None and amt<=cap: break
    return s
for amt in (10_000_000,50_000_000):
    print(f"== {amt//10_000:,}만원")
    rows=sorted(((yearly(amt,t),k) for k,t in tiers.items()),reverse=True)
    for y,k in rows:
        print(f"{k:28s} 실제금리 {y/amt*100:5.2f}% · 세전 월 {y/12:,.0f}원 · 세후 월 {y*0.846/12:,.0f}원")
