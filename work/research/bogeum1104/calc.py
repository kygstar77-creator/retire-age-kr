# 2026-11-04 firemap-write: 보금자리론(아낌e) 달별 금리로 3억·30년 원리금균등 월 상환액 (raw/hist/*.html·raw/rate.html = 주택금융공사 금리안내)
import sys
sys.stdout.reconfigure(encoding='utf-8')
R = [('2025-12-01', 3.85), ('2026-01-01', 4.10), ('2026-02-01', 4.25), ('2026-04-01', 4.55), ('2026-05-01', 4.80),
     ('2026-07-07', 5.10), ('2026-11-09', 5.20)]  # 아낌e 30년. 03·06·08·09·10월·11/1은 그대로
def pay(P, r, n):
    i = r / 100 / 12
    return P * i / (1 - (1 + i) ** -n)
P, N = 300_000_000, 360
print('§1 아낌e 30년 금리·3억 30년 월 상환액·30년 이자 합계')
base = pay(P, 3.85, N)
for d, r in R:
    m = pay(P, r, N)
    print(f'{d} {r:.2f}% 월 {m:,.0f}원 · 1년 전 대비 월 +{m-base:,.0f} · 30년 이자 {m*N-P:,.0f}')
m0, m1 = pay(P, 3.85, N), pay(P, 5.20, N)
print(f'\n§2 3.85→5.20 (+{5.20-3.85:.2f}%p) 월 차 {m1-m0:,.0f} · 1년 {(m1-m0)*12:,.0f} · 30년 이자 차 {(m1-m0)*N:,.0f}')
a, b = pay(P, 5.10, N), pay(P, 5.20, N)
print(f'§3 8일까지(5.10) vs 9일부터(5.20) 월 차 {b-a:,.0f} · 30년 {(b-a)*N:,.0f}')
print('\n§4 다른 금액(5.10 vs 5.20 / 3.85 vs 5.20, 30년)')
for p in (200_000_000, 360_000_000, 420_000_000):
    print(f'{p//10**8 if p%10**8==0 else p/10**8}억 월 {pay(p,5.10,N):,.0f}→{pay(p,5.20,N):,.0f} (+{pay(p,5.20,N)-pay(p,5.10,N):,.0f}) · 1년 전 {pay(p,3.85,N):,.0f} (+{pay(p,5.20,N)-pay(p,3.85,N):,.0f})')
print('\n§5 다른 만기 3억(11/9 금리, 아낌e 10·20년)')
for n, r0, r1 in ((120, 3.65, 5.00), (240, 3.80, 5.15)):
    print(f'{n//12}년 {r0}→{r1} 월 {pay(P,r0,n):,.0f}→{pay(P,r1,n):,.0f} (+{pay(P,r1,n)-pay(P,r0,n):,.0f})')
print('\n§6 우대 0.3%p(신혼) 30년 5.20-0.30=4.90 월', f'{pay(P,4.90,N):,.0f}', '· 규제지역 +0.2 5.40 월', f'{pay(P,5.40,N):,.0f}')
