# ltc1005 계산 — 장기요양보험료(2026) 직장가입자 월급별·지역가입자 건강보험료별. 10원 미만 버림. firemap-write 2026-10-05
from fractions import Fraction as F
RATE_H=F(719,10000); RATE_L=F(9448,1000000)   # 시행령 제44조①, 노인장기요양법 시행령 제4조
RATIO=F(1314,10000)  # 법 제9조① 건보료율 대비 비율 9448/71900=0.131404.. 소수점 다섯째자리 반올림 -> 0.1314
def fl(x): return int(x//10*10)
print('비율(법 제9조①)', float(RATE_L/RATE_H), '→ 0.1314 = 13.14%')
print('== 직장가입자 월급(보수월액)별')
for w in [2500000,3000000,4000000,5000000,7000000]:
    h=fl(w*RATE_H); l1=fl(w*RATE_L); l2=fl(h*RATIO)
    print(f'{w:>8} 건보 {h:>7} 장기요양 {l1:>6} (건보×13.14%: {l2:>6}) 합 {h+l1:>7} | 근로자 몫 건보 {h//2:>7} 장기 {l1//2:>6} 합 {h//2+l1//2:>7}')
print('== 2025 0.9182% vs 2026, 월급 300만')
a=fl(3000000*F(9182,1000000)); b=fl(3000000*RATE_L); print(a,b,b-a,(b-a)//2)
print('== 지역가입자 건강보험료별')
for h in [100000,150000,200000,300000,400000]:
    print(h, fl(h*RATIO), fl(h*F(9448,71900)), h+fl(h*RATIO))
