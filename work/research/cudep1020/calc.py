# cudep1020 계산 — 조특법 89조의3(2025.12.23 개정)·농특세법 5조①2호(감면세액의 10%)·소득세법 129조(14%)+지방소득세(10%)
P=30_000_000; r=0.044  # 3천만원 한도·특판 4.4%(티끌 카페 10/20 신협 4.3~4.41%) 1년 단리
I=P*r
cases={
 '은행 일반(15.4%)':0.154,
 '조합 비과세(농특세 1.4%)':0.014,                 # 감면세액 14% x 10%
 '조합 2026 가입·소득기준 초과(5%+농특 0.9%)':0.05+(0.14-0.05)*0.10,
 '조합 2027 가입·소득기준 초과(9%+농특 0.5%)':0.09+(0.14-0.09)*0.10,
}
print(f'원금 {P:,} · 금리 {r*100}% · 세전 이자 {I:,.0f}')
for k,t in cases.items():
    net=I*(1-t); eq=r*(1-t)/(1-0.154)
    print(f'{k}: 세율 {t*100:.1f}% 세금 {I*t:,.0f} 세후 {net:,.0f} · 은행 환산 세전 {eq*100:.3f}%')
print('비과세-은행 차', f'{I*(0.154-0.014):,.0f}')
print('5.9%-은행 차', f'{I*(0.154-0.059):,.0f}')
# 은행 최고 기본금리 3.92%(finlife 2026-09 공시, 전북은행) 3천만원 세후
b=P*0.0392*(1-0.154); print('은행 3.92% 세후',f'{b:,.0f}', '조합 4.4% 비과세 세후와 차', f'{I*0.986-b:,.0f}')
# 1천만원·2천만원
for p in (10_000_000,20_000_000): print(p, '비과세-은행 차', f'{p*r*0.14:,.0f}')
