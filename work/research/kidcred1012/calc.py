#       자녀 1명 20,830원·2명 45,830원·3명부터 +33,330원 / 3월 1일 이후 원천징수분부터(부칙 제36129호 제15조), 1~2월은 옛 표 12,500·29,160·+25,000
# 2017년생: 소득세법 부칙 제2조③ 경과(9세 이상) 적용 제외 → 13세 이상(2030년)부터, 아동수당법 부칙<제21489호> 제2조② 2026~2029년 매월 아동수당
# 가정: 1월부터 회사에 그 자녀를 '8세 이상 20세 이하 자녀'로 신고, 표 세액이 공제액보다 커서 0원 아래로 안 내려감, 지방소득세 10% 따로
import sys; sys.stdout.reconfigure(encoding='utf-8')
OLD = {1: 12500, 2: 29160}; NEW = {1: 20830, 2: 45830}
def tbl(t, n):
    if n == 0: return 0
    if n <= 2: return t[n]
    return t[2] + (n - 2) * (25000 if t is OLD else 33330)
def kidcr(n):
    return 0 if n == 0 else 250000 if n == 1 else 550000 + (n - 2) * 400000
def w(x): return f'{round(x):,}원'
print('2026년 나이(연도 기준): 2016년생 10세 · 2017년생 9세 · 2018년생 8세')
for label, decl, cred in [('2016년생 1명', 1, 1), ('2017년생 1명', 1, 0), ('2018년생 1명', 1, 0), ('2016년생+2017년생 2명', 2, 1), ('2017년생+2018년생 2명', 2, 0)]:
    less = tbl(OLD, decl) * 2 + tbl(NEW, decl) * 10
    c = kidcr(cred)
    gap = less - c
    print(f'[{label}] 월급에서 덜 뗀 소득세 {w(less)}(1~2월 {w(tbl(OLD,decl))}×2 + 3~12월 {w(tbl(NEW,decl))}×10) · 연말정산 자녀세액공제 {w(c)} '
          f'· 차이 소득세 {w(gap)} · 지방소득세 포함 {w(gap*1.1)}')
print('2027년 소득분 10세 이상: 2016년생 이전만(2017년생은 13세 되는 2030년, 2018년생 9세는 못 받음)')
# 작년(2025년 소득분, 8세 이상·옛 표 12,500원 12개월)과 비교 — 레드팀 10/11 지적
y25_2017 = 250000 - 12500 * 12          # 2017년생은 2025년 8세: 공제 25만 − 덜 뗀 15만 = 10만 더 돌려받음
print(f'[작년 대비] 2017년생 1명: 2025년 {w(y25_2017*1.1)} 더 받음 → 2026년 {w(-233300*1.1)} · 차이 {w((y25_2017+233300)*1.1)}')
print('[작년 대비] 2018년생 1명: 2025년 7세라 공제·감면 둘 다 없음 → 2026년 −256,630원 · 차이 256,630원')
print('2018년생 자녀세액공제: 2027 9세(10세 기준)·2028 10세(11)·2029 11세(12)·2030 12세(13) 모두 0원 → 2031년 13세부터')
