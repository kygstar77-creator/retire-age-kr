# 숫자 대조(numcheck): props 글자 속 숫자 덩이는 calc 두 개·대본에 그대로 있어야 한다
SKIP = {'pre', 'seed', 'audio', 'src', 'license', 'kind', 'icon', 'c', 'c1', 'c2', 'from', 'x', 'side', 'dir', 'max', 'at', 'at2', 'lit', 'done', 'step', 'mode', 'chapter'}
def strings(x):
    if isinstance(x, dict):
        for k, v in x.items():
            if k in SKIP: continue
            yield from strings(v)
    elif isinstance(x, list):
        for v in x:
            if not isinstance(v, (int, float)): yield from strings(v)
    elif isinstance(x, str): yield x
