import sys; sys.stdout.reconfigure(encoding='utf-8')
def normal(p):
    r = 0.01 if p <= 6e8 else (0.03 if p > 9e8 else round((p*2/3e8 - 3)/100, 4))
    return r, p*r, p*r*0.5*0.2
for p in (6e8, 10e8, 15e8):
    r, a, e = normal(p); ha, he = p*0.08, p*0.004
    print(f'{p/1e8:.0f}억: 일반 {r*100:.2f}% 취득세 {a/1e4:,.0f}만 + 지방교육세 {e/1e4:,.0f}만 = {(a+e)/1e4:,.0f}만 | 중과 8% {ha/1e4:,.0f}만 + 교육세 0.4% {he/1e4:,.0f}만 = {(ha+he)/1e4:,.0f}만 | 차이 {(ha+he-a-e)/1e4:,.0f}만')
