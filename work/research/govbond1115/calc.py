# 개인투자용 국채 11월(재경부 10/29) vs 10월(9/30) — 1천만원 만기 세전·세후
P=10_000_000
oct_={'3c':(3.875,0),'5':(4.275,0.05),'10':(4.510,0.28),'20':(4.520,0.43)}
nov={'3c':(3.940,0),'5':(3.935,0.10),'10':(4.155,0.63),'20':(4.155,0.79)}
yrs={'3c':3,'5':5,'10':10,'20':20}
out=[]
def amt(r,n): return P*((1+r/100)**n-1)
for k in ['3c','5','10','20']:
    n=yrs[k]; ro=sum(oct_[k]); rn=sum(nov[k])
    io=amt(ro,n); inn=amt(rn,n)
    out.append(f"[{k}] 10월 {oct_[k][0]}+{oct_[k][1]}={ro:.3f}% 세전이자 {io:,.0f}({io/P*100:.1f}%) | 11월 {nov[k][0]}+{nov[k][1]}={rn:.3f}% 세전이자 {inn:,.0f}({inn/P*100:.1f}%) 세후(15.4%) {inn*0.846:,.0f} | 차이 {inn-io:,.0f} · 표면 {nov[k][0]-oct_[k][0]:+.3f}p 가산 {nov[k][1]-oct_[k][1]:+.2f}p 합 {rn-ro:+.3f}p")
# 3년 이표채
out.append(f"[3i] 11월 3.940% 단리 3년 {P*0.0394*3:,.0f}({3.94*3:.2f}%) · 10월 {P*0.03875*3:,.0f}")
# 가산금리 몫: 10년물 11월 가산 없으면
for k in ['10','20','5']:
    n=yrs[k]; s,a=nov[k]
    out.append(f"[가산 몫 {k}] 표면만 {amt(s,n):,.0f} · 가산 더하면 {amt(s+a,n):,.0f} · 가산 몫 {amt(s+a,n)-amt(s,n):,.0f}")
# 예금 비교(가정): ECOS 2026-09 1년 정기예금 신규취급 평균 3.57%를 해마다 다시 넣는다고(세전 복리)
for n in (5,10):
    out.append(f"[예금 가정] 3.57% {n}년 해마다 재예치 세전 {amt(3.57,n):,.0f} · 매년 세금 떼고 굴리면 {P*((1+0.0357*0.846)**n-1):,.0f}")
# 세후: 국채 분리과세 만기 일시 15.4%
out.append(f"[세후 10년 11월] {amt(4.785,10)*0.846:,.0f}")
open('calc_out.txt','w',encoding='utf-8').write('\n'.join(out)+'\n'); print('\n'.join(out))
