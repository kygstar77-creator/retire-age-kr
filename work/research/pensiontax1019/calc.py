def gongje(g):
    if g<=3_500_000: d=g
    elif g<=7_000_000: d=3_500_000+(g-3_500_000)*.4
    elif g<=14_000_000: d=4_900_000+(g-7_000_000)*.2
    else: d=6_300_000+(g-14_000_000)*.1
    return min(d,9_000_000)
def comb(g):
    base=g-gongje(g)-1_500_000
    base=max(base,0)
    t= base*.06 if base<=14_000_000 else 840_000+(base-14_000_000)*.15
    return base,t,t*1.1
