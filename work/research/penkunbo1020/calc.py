# -*- coding: utf-8 -*-
# 국민연금 월액별 '금융소득 1,000만원 → 1,001만원' 건보료 계단 (지역가입자 1인·재산 0·다른 소득 0·2026)
# 근거: 시행령 41조①5호·44조①(7.19%) · 시행규칙 44조①단서·②2호(50%)·③(28만원 이하→하한) · 고시 2025-222 제3조(하한 20,160) · 장기요양 시행령 4조(0.9448%)
RATE, LTC, FLOOR, CAP = 0.0719, 0.009448, 20160, 4591740
def f10(x): return int(x // 10 * 10)
def prem(monthly_income):
    if monthly_income <= 280000:
        h = FLOOR
    else:
        h = min(f10(monthly_income * RATE), CAP)
    l = f10(h * LTC / RATE)
    return h, l, h + l
def case(pension_m, fin_y):
    inc_y = pension_m * 12 * 0.5 + (fin_y if fin_y > 10_000_000 else 0)
    return prem(inc_y / 12)
out = []
for p in [0, 300000, 500000, 560000, 570000, 700000, 1000000, 1500000, 2000000, 2500000]:
    a = case(p, 10_000_000); b = case(p, 10_010_000)
    out.append(f"연금 월 {p:,}원: 1,000만 {a[2]:,}원 → 1,001만 {b[2]:,}원 · 월 {b[2]-a[2]:,}원 · 연 {(b[2]-a[2])*12:,}원")
# 계단이 같아지는 연금 경계: 연금 50% 월액 > 280,000 → 연금 월 > 560,000
out.append("경계: 연금 반영분 월 28만원 초과 = 연금 월 56만원 초과면 하한 위 → 계단 = 금융소득 월 834,167원 전부")
# 배당 1,000만원 '아래' 유지 시 필요한 원금 예: 연 4% 배당이면 2.5억 (산수 예시)
out.append(f"금융소득 1,001만원 월환산 {10_010_000/12:,.0f}원")
for p in [1000000, 1500000, 2000000]:
    for fy in [9_000_000, 10_000_000, 12_000_000, 15_000_000, 20_000_000]:
        out.append(f"  연금 {p:,} + 금융 {fy:,}: {case(p, fy)[2]:,}원")
open('calc_out.txt','w',encoding='utf-8').write("\n".join(out)+"\n")
print("\n".join(out))
