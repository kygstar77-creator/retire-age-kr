# 시행령 제44조①(보험료율 1만분의 719) · 시행규칙 제44조②2호·③(지역가입자 연금·근로소득 100분의 50 반영)
# 시행규칙 제44조① 단서(분리과세 이자·배당 1천만원 이하는 합산 안 함 — 넘으면 전액)
# 별표 1의2 제1호가목(소득 합계 연 2천만원 이하) · 장기요양보험료 = 건강보험료 × 13.14%(복지부 2025.11.4)
# 탈락자 경감 = 시행규칙 부칙<제907호, 2022.9.1> 제3조: 2022.9.1 뒤 소득요건으로 '처음' 탈락한 세대만, 오른 몫에서
#   80%(~2023.10분)·60%(~2024.10분)·40%(~2025.10분)·20%(2025.11~2026.8분) → 2026년 9월분부터 없음, 지금 새로 탈락하면 0
# 재산분·하한액은 넣지 않는다(재산 0 가정).
RATE, LTC = 0.0719, 0.1314
def jiyeok(annual_pension, fin=0):
    fin_in = fin if fin > 10_000_000 else 0
    monthly = (annual_pension * 0.5 + fin_in) / 12
    hi = round(monthly * RATE); return hi, round(hi * LTC), hi + round(hi * LTC)
def dependent_ok(annual_pension, fin=0):
    return annual_pension + (fin if fin > 10_000_000 else 0) <= 20_000_000
print('월 연금(만원) | 연 합계 | 피부양자 | 건강보험 | 장기요양 | 합계/월 | 10년 합(만원)')
for m in [150, 160, 166, 167, 170, 180, 200, 250]:
    a = m * 12 * 10000
    if dependent_ok(a): print(f'{m:>4} | {a/1e4:>6,.0f}만 | 유지 | 0 | 0 | 0원 | 0'); continue
    h, l, t = jiyeok(a); print(f'{m:>4} | {a/1e4:>6,.0f}만 | 탈락 | {h:,} | {l:,} | {t:,}원 | {t*120/1e4:,.0f}')
print('경계 월액', 20_000_000/12)
# 경감: 2022.9 이후 처음 탈락해 경감 받던 사람, 월 170만 연금 기준(올해 요율로 셈 — 그해 요율 아님, 비교용)
h, l, t = jiyeok(170*12*10000)
print('170만 경감 20%(2026.8월분까지) 건강보험분', round(h*0.8), '→ 9월분부터', h, '(장기요양 경감 여부 확인 안 함)')
print('지금 새로 탈락: 경감 0 →', t)
# 이자·배당 섞인 경우(제44조① 단서)
for pen, fin in [(1800, 300), (1800, 999), (1000, 1100), (1800, 1100)]:
    a, f = pen*10000, fin*10000
    ok = dependent_ok(a, f)
    print(f'연금 {pen}만 + 이자·배당 {fin}만 → 소득으로 셈 {(a+(f if f>10_000_000 else 0))/1e4:,.0f}만 · 피부양자 {"유지(공단 확인 권함)" if ok else "탈락"}' + ('' if ok else f' · 월 {jiyeok(a,f)[2]:,}원'))
