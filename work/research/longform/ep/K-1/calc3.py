# K-1 calc3 (2026-10-21 youtube-loop) — 대본 보탬용: 3억·30년 변동형 월 납입, 2억 예금 세후 차, 고정−변동 차 · 입력은 calc_out.txt 값(한은 ECOS 121Y002·121Y006)
def pmt(P, r, n):
    i = r / 100 / 12
    return P * i / (1 - (1 + i) ** -n)
print('== 3억·30년 원리금균등 변동형 2025.08 4.08% → 2026.08 4.53%')
a, b = pmt(3e8, 4.08, 360), pmt(3e8, 4.53, 360)
print(f' 월 {a:,.0f}원 → {b:,.0f}원 (차 +{b-a:,.0f}원, 한 해 +{(b-a)*12:,.0f}원)')
print('== 2억 1년 정기예금 세후(15.4%) 2.51% → 3.39%')
x, y = 2e8 * 0.0251 * 0.846, 2e8 * 0.0339 * 0.846
print(f' {x:,.0f}원 → {y:,.0f}원 (차 +{y-x:,.0f}원)')
print('== 고정형 − 변동형 평균 (%p)')
for m, f, v in (('202508', 3.94, 4.08), ('202608', 4.88, 4.53)):
    print(f' {m}: {f} − {v} = {f-v:+.2f}')
