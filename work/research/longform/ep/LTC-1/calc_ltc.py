# LTC-1 계산 — 원문: src/mohw_2026suga.txt(복지부 2025-11-04 붙임2), src/mohw_2027suga.txt(복지부 2026-10-30 붙임2)
# 비급여(식재료비·상급침실료)는 원문에 공식 평균이 없어 넣지 않는다.
SISEOL = {  # 노인요양시설 1일 수가, 본인부담(20%)
    "1등급": {"26": (93070, 18614), "27": (96380, 19276)},
    "2등급": {"26": (86340, 17268), "27": (89410, 17882)},
    "3~5등급": {"26": (81540, 16308), "27": (84440, 16888)},
}
JAEGA = {  # 재가급여 월 한도액
    "1등급": (2512900, 2891400), "2등급": (2331200, 2682300), "3등급": (1528200, 1586300),
    "4등급": (1409700, 1462000), "5등급": (1208900, 1254900), "인지지원등급": (676320, 700200),
}

print("## 요양원(노인요양시설) 본인부담 — 급여 부분만, 30일·31일")
for g, v in SISEOL.items():
    (s26, b26), (s27, b27) = v["26"], v["27"]
    assert round(s26 * 0.2) == b26 and round(s27 * 0.2) == b27, g  # 20% 확인
    print(f"{g}: 2026 30일 {b26*30:,} / 31일 {b26*31:,} · 2027 30일 {b27*30:,} / 31일 {b27*31:,}"
          f" · 30일 차 +{(b27-b26)*30:,} · 수가 인상 {s27/s26-1:.2%} · 월 수가 전체(30일) 2026 {s26*30:,} / 2027 {s27*30:,}")
    # 감경(본인부담 40%·60% 감경 → 12%·8%)은 법령 원문 확인 전이라 참고 값만
    print(f"   참고(감경 비율 법령 확인 필요): 40% 감경 30일 {round(s26*0.12)*30:,} · 60% 감경 30일 {round(s26*0.08)*30:,} (2026)")

print("\n## 재가 월 한도 vs 시설 월 수가(30일)")
for g, (h26, h27) in JAEGA.items():
    line = f"{g}: 2026 {h26:,} → 2027 {h27:,} ({h27/h26-1:.1%}) · 재가 본인부담 15% 한도 다 쓰면 2026 {round(h26*0.15):,} / 2027 {round(h27*0.15):,}"
    key = g if g in SISEOL else "3~5등급"
    if g not in ("인지지원등급",):
        s27 = SISEOL[key]["27"][0] * 30
        s26 = SISEOL[key]["26"][0] * 30
        line += f" · 시설 월 수가 대비 2026 {h26/s26:.1%} / 2027 {h27/s27:.1%}"
    print(line)
