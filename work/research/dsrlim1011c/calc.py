# 스트레스 금리: 수도권·규제지역 3.0%(변동 100%·5년 혼합형 80%·5년 주기형 40%, 10·15 대책 원문 p.11)
#               지방 2026.12.31까지 2단계 0.75%(1.5%×50%), 3단계 적용 시 1.5%(금융위 6/18·은행연합회 6/30)
import sys; sys.stdout.reconfigure(encoding='utf-8')
INC = 5000e4; CAP = INC * 0.40; N = 360
def limit(r):  # 연 원리금 CAP 안에서 빌릴 수 있는 원금
    m = r / 100 / 12
    pay = CAP / 12
    return pay * (1 - (1 + m) ** -N) / m
def pay(L, r):
    m = r / 100 / 12
    return L * m / (1 - (1 + m) ** -N)
S = [('스트레스 없음 · 변동 4.53%', 4.53, 4.53),
     ('수도권 · 변동형', 4.53, 4.53 + 3.0),
     ('수도권 · 5년 혼합형', 4.88, 4.88 + 3.0 * 0.8),
     ('수도권 · 5년 주기형', 4.88, 4.88 + 3.0 * 0.4),
     ('지방 · 변동형(지금 0.75%)', 4.53, 4.53 + 0.75),
     ('지방 · 변동형(3단계 1.5% 적용 시)', 4.53, 4.53 + 1.5)]
base = limit(4.53)
for name, real, dsr in S:
    L = limit(dsr)
    print(f'{name}: 심사금리 {dsr:.2f}% → 한도 {L/1e4:,.0f}만원 (스트레스 없을 때보다 {(base-L)/1e4:,.0f}만원 적음, {(base-L)/base*100:.1f}%) · 실제 금리 {real}%로 갚는 월 {pay(L, real)/1e4:,.1f}만원')
print('연 원리금 상한', CAP/1e4, '만원 · 월', CAP/12/1e4, '만원')
