# 개인투자용 국채 10월물(2026-10) 직접 계산 — 원문 raw/moef_20260930.txt
P = 10_000_000
rates = {'3y': (3.875, 0, 3), '5y': (4.275, 0.05, 5), '10y': (4.510, 0.28, 10), '20y': (4.520, 0.43, 20)}
for k, (c, a, n) in rates.items():
    tot = (1 + (c + a) / 100) ** n - 1
    print(f'{k} 만기 세전 이자율 {tot*100:.1f}% · 1천만원 이자 {P*tot:,.0f} · 만기 {P*(1+tot):,.0f}')
# 10년물: 만기 vs 중도환매(발행 1년 뒤부터, 표면 4.510% 단리, 가산금리·복리·분리과세 없음)
c, a = 4.510, 0.28
print('\n10년물 1천만원, 해마다 중도환매 vs 같은 해까지 만기형 복리(가산금리 포함)였다면')
for y in range(1, 11):
    simple = P * c / 100 * y
    comp = P * ((1 + (c + a) / 100) ** y - 1)
    print(f'{y}년 뒤: 중도환매 이자 {simple:,.0f} · 복리+가산 {comp:,.0f} · 차이 {comp-simple:,.0f}')
# 만기 세후(분리과세 14% + 지방소득세 1.4% = 15.4%)
tot10 = P * ((1 + (c + a) / 100) ** 10 - 1)
print(f'\n10년 만기 이자 {tot10:,.0f} · 분리과세 15.4% 세금 {tot10*0.154:,.0f} · 세후 이자 {tot10*0.846:,.0f}')
# 금융소득 종합과세 대상자가 같은 이자를 종합과세로 냈다면(지방세 포함 한계세율 예시)
for r in (26.4, 38.5, 41.8):
    print(f'  한계세율 {r}%면 세금 {tot10*r/100:,.0f} · 분리과세와 차이 {tot10*(r-15.4)/100:,.0f}')
