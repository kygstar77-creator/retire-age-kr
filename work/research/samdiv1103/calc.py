# samdiv1103 계산 — DART 배당 결정 원문(raw/*.txt)·소득세법 제129조·지방세법 제103조의13·건보 시행규칙 제44조·시행령 제41조④
import math
Q3 = 4601                      # 2026-10-29 현금·현물배당결정 20261029800101
Y2026 = {'2025 결산(2026-03-18 주총)': 566, '2026 1분기': 372, '2026 2분기': 374, '2026 3분기': 4601}   # 보통주
PER = sum(Y2026.values())
BEFORE = PER - Q3
CLOSE = 229000                 # 2026-11-02 종가(야후 005930.KS)
def tax(gross):
    inc = math.floor(gross * 0.14)        # 소득세 14%(제129조①2나), 원 미만 버림 가정
    loc = math.floor(inc * 0.10)          # 지방소득세 = 소득세의 10%(지방세법 제103조의13)
    return inc, loc, gross - inc - loc
print('2026년 1주당 배당 합계(보통주):', PER, '/ 3분기 빼면', BEFORE)
for n in (100, 500, 1000):
    g = n * Q3; i, l, net = tax(g)
    print(f'{n}주 3분기 세전 {g:,} 소득세 {i:,} 지방 {l:,} 실수령 {net:,}')
for line, lab in ((10_000_000, '1천만원(건보 지역가입자 금융소득 합산 시작)'), (20_000_000, '2천만원(금융소득 종합과세·직장 보수외 소득)')):
    n = line // PER + 1
    n0 = line // BEFORE + 1
    print(f'{lab}: {n:,}주부터 넘음({n*PER:,}원, {n-1:,}주={(n-1)*PER:,}원) · 11/2 종가 평가액 {n*CLOSE:,}원 · 3분기 없을 때 {n0:,}주({n0/n:.1f}배)')
n = (10_000_000 - 5_000_000) // PER + 1
print(f'예금 이자 500만원 있을 때 1천만원 넘는 삼성전자 주식 수: {n}주({n*PER:,}원)')
print(f'3분기 비중: {Q3/PER*100:.1f}%')
PREF = PER + 1   # 우선주 2025 결산 567원
for line in (10_000_000, 20_000_000):
    n = line // PREF + 1
    print(f'우선주(1주당 {PREF}원) {line:,}원 넘는 주식 수: {n}주({n*PREF:,}원)')
