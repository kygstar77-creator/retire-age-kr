# K-1 calc2 (youtube-loop 2026-10-19): COFIX 원문(은행연합회) 대조 · 5년 고정 뒤 갱신 · 주담대-예금 차이
import json
d = json.load(open('raw/series.json', encoding='utf-8'))
cf = json.load(open('raw/cofix.json', encoding='utf-8'))['rows']
def pay(P, r, n): r /= 1200; return P * r / (1 - (1 + r) ** -n)
def bal(P, r, n, k): r /= 1200; m = pay(P, r * 1200, n); return P * (1 + r) ** k - m * ((1 + r) ** k - 1) / r
print('== A. COFIX(은행연합회, 대상월) 2025/08 → 2026/08 → 2026/09')
for i, nm in enumerate(['신규취급액', '잔액', '신잔액'], 1):
    a, b, c = cf['2025/08'][i], cf['2026/08'][i], cf['2026/09'][i]
    print(f' {nm}: {a} → {b} ({b-a:+.2f}%p) → 9월 {c} ({c-b:+.2f}%p)')
print(f" 같은 1년 한은 변동형 주담대 {d['mvar']['202508']} → {d['mvar']['202608']} ({d['mvar']['202608']-d['mvar']['202508']:+.2f}%p)"
      f" · 고정형 {d['mfix']['202508']} → {d['mfix']['202608']} ({d['mfix']['202608']-d['mfix']['202508']:+.2f}%p)"
      f" · 정기예금 1년 {d['dep1']['202508']} → {d['dep1']['202608']} ({d['dep1']['202608']-d['dep1']['202508']:+.2f}%p)")
print('== B. 2021년 8월 고정형으로 3억·30년 → 5년 뒤(2026.08) 같은 고정형 금리로 다시 정하면 (가정: 원리금균등, 남은 25년)')
r0, r1 = d['mfix']['202108'], d['mfix']['202608']
m0 = pay(3e8, r0, 360); B = bal(3e8, r0, 360, 60); m1 = pay(B, r1, 300)
print(f' {r0}% 월 {m0:,.0f}원 · 5년 뒤 남은 원금 {B:,.0f}원 · {r1}%로 남은 25년 월 {m1:,.0f}원 (차 {m1-m0:+,.0f}원, 한 해 {12*(m1-m0):+,.0f}원)')
print('== C. 주담대 − 정기예금(전체) 금리 차이 (한은 신규취급액, 예대금리차 공식 지표 아님)')
for m in ['202108', '202508', '202608']:
    print(f" {m}: 주담대 {d['mtg'][m]} − 예금 {d['dep'][m]} = {d['mtg'][m]-d['dep'][m]:.2f}%p")
print('== D. 1억 정기예금 1년 세후 이자 (15.4%) 2021.08 vs 2026.08')
for m in ['202108', '202508', '202608']:
    print(f" {m} {d['dep1'][m]}% → {1e8*d['dep1'][m]/100*(1-0.154):,.0f}원")
