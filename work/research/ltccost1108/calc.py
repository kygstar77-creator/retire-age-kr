# 요양원(노인요양시설, 요양보호사 2.1명당 1명 이상) 30일 본인부담 — 공단 2026.1.1 하루 급여비용 × 30 × 본인부담률
# 본인부담률: 시행령 제15조의8 시설 20% · 감경 고시 제2조 60%/40% 감경 → 8%/12% · 법 제40조② 의료급여 1호 0%
import sys; sys.stdout.reconfigure(encoding='utf-8')
day = {'1등급': 93070, '2등급': 86340, '3~5등급': 81540}
rate = {'일반 20%': .20, '40% 감경 12%': .20*.6, '60% 감경 8%': .20*.4}
for g, d in day.items():
    tot = d*30
    print(g, '30일 급여비용', f'{tot:,}', ' | '.join(f'{k} {round(tot*r):,}' for k, r in rate.items()))
