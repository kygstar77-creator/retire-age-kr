# 법정 전월세 전환 상한(주택임대차보호법 7조의2·시행령 9조: min(10%, 기준금리+2%)) — 기준금리 ECOS 722Y001 일별(2026-10-22 받음)
periods = [('~2026-07-15', 2.50), ('2026-07-16~08-26', 2.75), ('2026-08-27~(10/22 동결)', 3.00)]
amts = [5000, 10000, 20000, 30000]  # 만원
out = []
for name, b in periods:
    r = min(10.0, b + 2.0)
    row = [f'{name} 기준금리 {b:.2f}% → 상한 {r:.2f}%']
    for a in amts:
        m = a * 10000 * r / 100 / 12
        row.append(f'  보증금 {a:,}만원 → 월 {m:,.0f}원')
    out.append('\n'.join(row))
d = 10000 * 10000 * (5.0 - 4.5) / 100 / 12
out.append(f'1억 기준 4.5%→5.0% 차이: 월 {d:,.0f}원 · 연 {d*12:,.0f}원')
# 생활법령 국토부 예시 검산(전세 5억 → 보증금 3억 + 월세): 지금 5%면
for keep in (30000, 20000):
    conv = 50000 - keep
    out.append(f'전세 5억 → 보증금 {keep:,}만원: 월 {conv*10000*0.05/12:,.0f}원(5%)')
s = '\n\n'.join(out); print(s); open('calc_out.txt', 'w', encoding='utf-8').write(s + '\n')
