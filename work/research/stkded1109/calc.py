# stkded1109 계산 — 주식 양도소득 기본공제 250만원(소득세법 제103조)을 빠뜨렸을 때 더 낸 세금
# 세율: 소득세법 제104조①11·12(국외주식 일반 20%·중소기업 10%, 대주주 1년 미만 30%), 지방소득세 = 양도소득세의 10%(국세청 11/3 문답 7)
# 경정청구: 국세기본법 제45조의2① 법정신고기한이 지난 뒤 5년 · 확정신고기한 다음 해 5월 31일(소득세법 제110조①)
import os, sys
sys.stdout.reconfigure(encoding='utf-8')
os.chdir(os.path.dirname(os.path.abspath(__file__)))
out = []
def p(*a):
    s = ' '.join(str(x) for x in a); print(s); out.append(s)

DED = 2_500_000
p('# 1) 250만원을 빠뜨렸을 때 더 낸 세금(본세+지방소득세, 가산금 빼고)')
for name, r in [('국외주식 일반 20%', 0.20), ('중소기업 주식 10%', 0.10), ('대주주 1년 미만 30%', 0.30)]:
    tax = DED * r; local = tax * 0.10
    p(f'{name}: 본세 {tax:,.0f} + 지방 {local:,.0f} = {tax+local:,.0f}')

p('# 2) 국세청 예시 대조(보도자료 참고1): 6,001,449원·30%')
g = 6_001_449
before = g * 0.30; after = (g - DED) * 0.30
p(f'반영 전 {before:,.0f} · 반영 후 {after:,.0f} · 차이 {before-after:,.0f} (보도자료 1,800,434·1,050,434·750,000)')
add = 750_000 * 0.031 * 567 / 365
p(f'가산금 750,000×3.1%×567/365 = {add:,.0f} (보도자료 36,110)')

p('# 3) 이익 200만원이면(250만원보다 적음) — 200만원만 공제, 남은 50만원은 다음 해로 안 넘어감(문답 10)')
g2 = 2_000_000
p(f'과세표준 {max(0, g2-DED):,} → 세금 0원 · 빠뜨렸다면 더 낸 돈 {g2*0.20*1.1:,.0f}')

p('# 4) 지식iN 495711401 꼴: 이익 1,200만원·손실 200만원(같은 해 해외주식)')
gain = 12_000_000 - 2_000_000
base = gain - DED
tax = base * 0.20
p(f'통산 {gain:,} → 과세표준 {base:,} → 양도소득세 {tax:,.0f} + 지방 {tax*0.1:,.0f} = {tax*1.1:,.0f}')
nodeduct = gain * 0.20 * 1.1
p(f'공제를 빠뜨리면 {nodeduct:,.0f} → 더 내는 돈 {nodeduct - tax*1.1:,.0f}')

p('# 5) 경정청구 기한(해외주식 확정신고 기준: 다음 해 5월 31일 + 5년)')
for y in range(2021, 2026):
    p(f'{y}년에 판 것 → 신고기한 {y+1}.5.31 → 경정청구 {y+6}.5.31까지')

open('calc_out.txt', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
