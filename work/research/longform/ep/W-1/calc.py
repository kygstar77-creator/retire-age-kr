"""W-1 1화(10/11 공개) 계산 — '이번 주 뉴스가 내 돈에 얼마'. 숫자는 원문 raw/와 facts_*.txt만.
출처: 삼성전자 DART 공시 3건(w1009/raw/dart_*.txt), 한국은행 ECOS(코스피·원달러 매매기준율, facts_2026-10-09.txt),
야후 파이낸스 일별 종가(w1009/raw/yh_*.json — 삼성전자 005930.KS, SPY), FRED(CPIAUCSL), BLS·한국은행·연준 일정표(브라우저 확인 10/9).
다시 돌리기: 미국 금요일(10/9) 종가가 들어온 뒤(한국 10/10 06시 이후) `py -3.12 w1009/fetch_us.py` → `py -3.12 calc.py`."""
import json, os, sys, datetime as dt
sys.stdout.reconfigure(encoding='utf-8')
H = os.path.dirname(os.path.abspath(__file__)); W = os.path.join(H, 'w1009', 'raw')
def yh(sym):
    j = json.load(open(os.path.join(W, f'yh_{sym}.json')))['chart']['result'][0]
    tz = j['meta']['gmtoffset']
    return {dt.datetime.fromtimestamp(t + tz, dt.UTC).strftime('%Y-%m-%d'): v for t, v in zip(j['timestamp'], j['indicators']['quote'][0]['close']) if v}
out = []
def p(k, v): out.append(f'{k} = {v}'); print(out[-1])
TAX = 0.154  # 배당소득세 14% + 지방소득세 1.4% (소득세법 제129조·지방세법 제103조의3) — 원천징수
# 1) 삼성전자 잠정실적 (DART 20261008800004)
op_now, op_prev_q, op_yoy = 107.40, 89.49, 12.17
p('[A1] 삼성 3분기 영업이익(조원, 잠정)', op_now); p('[A2] 1년 전 3분기(조원)', op_yoy); p('[A3] 배수', round(op_now / op_yoy, 2))
p('[A4] 매출(조원)', 195.00); p('[A5] 공시 증감률(%)', 782.50)
# 2) 배당: 2025 3분기 370원(DART 20251030800075), 2026 2분기 374원(DART 20260730800137), 2분기 영업이익 89.49조
p('[B1] 2025 3분기 주당 배당(원)', 370); p('[B2] 2026 2분기 주당 배당(원)', 374); p('[B3] 2분기 영업이익(조원)', op_prev_q); p('[B8] 2분기 배당 지급 예정일(DART 20260730800137 7항)', '2026-08-28'); p('[B9] 2분기 배당 기준일(6항)', '2026-06-30 (6월 말)')
p('[B4] 영업이익 배수 2분기/1년전3분기', round(op_prev_q / op_yoy, 2))
for n in (100,):
    pre = 374 * n; p(f'[B5] {n}주 2분기 배당 세전(원)', pre); p(f'[B6] {n}주 세후(원, 15.4%)', round(pre * (1 - TAX)))
    p(f'[B7] {n}주 1년 전 3분기 세후(원)', round(370 * n * (1 - TAX)))
# 3) 삼성전자 주가 (야후 종가) — 한국 이번 주 거래일 10/6·10/7·10/8 (10/5 개천절 대체공휴일, 10/9 한글날)
s = yh('005930.KS'); a, b, c = s['2026-10-02'], s['2026-10-07'], s['2026-10-08']
p('[C1] 삼성 10/2 종가', int(a)); p('[C2] 10/7 종가', int(b)); p('[C3] 10/8 종가(실적 발표일)', int(c))
p('[C4] 발표일 하루 등락(%)', round((c / b - 1) * 100, 2)); p('[C5] 주간 등락(%)', round((c / a - 1) * 100, 2))
p('[C6] 100주 평가 10/2(원)', int(a * 100)); p('[C7] 100주 평가 10/8(원)', int(c * 100)); p('[C8] 100주 주간 차이(원)', int((c - a) * 100))
p('[C9] 주간 하락분 ÷ 세후 분기배당(배)', round((a - c) * 100 / round(374 * 100 * (1 - TAX)), 1))
# 4) 코스피 (ECOS) 7,003.74 → 6,625.93
k0, k1 = 7003.74, 6625.93; kr = (k1 / k0 - 1) * 100
p('[D1] 코스피 10/2', k0); p('[D2] 코스피 10/8', k1); p('[D3] 주간(%)', round(kr, 2)); p('[D4] 코스피 그대로 1천만원 차이(원)', round(10_000_000 * kr / 100))
# 5) 원달러 매매기준율 (ECOS) 1,359.60 → 1,339.20
f0, f1 = 1359.60, 1339.20
p('[E1] 원달러 10/2', f0); p('[E2] 원달러 10/8', f1); p('[E3] 등락(%)', round((f1 / f0 - 1) * 100, 2))
p('[E4] 1만 달러 원화 10/2(원)', round(10000 * f0)); p('[E5] 1만 달러 원화 10/8(원)', round(10000 * f1)); p('[E6] 환율만으로 차이(원)', round(10000 * (f1 - f0)))
# 6) 미국 S&P500 (SPY 종가, 달러) — 금요일 종가 들어오면 마지막 날이 10/9로 바뀐다
u = yh('SPY'); last = max(u); u0 = u['2026-10-02']; u1 = u[last]
p('[F1] SPY 마지막 날(금요일 종가 전이면 잠정)', last); p('[F2] SPY 10/2→마지막(%)', round((u1 / u0 - 1) * 100, 2))
p('[F3] 1만 달러 SPY 원화 10/2(원)', round(10000 * f0)); v1 = 10000 * u1 / u0 * f1
p('[F4] 1만 달러 SPY 원화 마지막(원, 환율 10/8 매매기준율)', round(v1)); p('[F5] 원화 차이(원)', round(v1 - 10000 * f0))
# 7) 다음 주 일정 — BLS: 9월 CPI 2026-10-14 08:30(미 동부) = 한국 10/14 21:30 · 한국은행 금통위 10/22(목) · 연준 FOMC 10/27~28 · 연준 9월 회의 의사록 10/7 공개
p('[G1] 미국 9월 CPI 발표(한국 시각)', '2026-10-14 21:30'); p('[G2] 금통위', '2026-10-22'); p('[G3] FOMC', '2026-10-27~28')
p('[G4] 삼성 3분기 확정 실적', '이사회 승인 때 재공시 예정(잠정실적 공시 4. 기타) · 날짜 공시 안 됨')
p('[G5] 1년 전 3분기 배당 결정일·기준일', '2025-10-30 · 2025-09-30 (DART 20251030800075)')
p('[G6] 미국 8월 CPI 1년 상승률(%, CPIAUCNS 2026-08 334.98 / 2025-08 323.976)', 3.4)
# [S] 말로 읽는 반올림 값(만원·근삿값) — 위 값에서만
p('[S1] 코스피 말(근삿값)', '7,000 → 6,600대 (7,003.74 → 6,625.93)')
p('[S2] 100주 평가 만원', f"{int(a*100/1e4):,} → {int(c*100/1e4):,} · 차이 {int((a-c)*100/1e4)}")
p('[S3] 100주 배당 말', '3만 7,400원 · 세후 3만 1,640원 · 3만원 남짓')
p('[S4] 코스피 1천만원 차이 만원(반올림)', round(10_000_000 * kr / 100 / 1e4))
p('[S5] 환율만 1만 달러 차이 만원(내림, "넘게")', int(10000 * (f0 - f1) / 1e4))
open(os.path.join(H, 'calc_out.txt'), 'w', encoding='utf-8').write(f'# W-1 1화 calc_out ({dt.datetime.now():%Y-%m-%d %H:%M})\n' + '\n'.join(out) + '\n')
