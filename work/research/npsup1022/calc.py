# npsup1022 계산 — 국민연금법 부칙(2025.4.2) 제4조 연도별 비율, 기준소득월액 상한 659만(2026.7~2027.6)
# 소득세 효과: 소득세법 제51조의3(연금보험료 전액 소득공제) × 한계세율(제55조) × 1.1(지방소득세)
RATE = {2026: 0.0475, 2027: 0.05, 2028: 0.0525, 2033: 0.065}  # 직장인 본인 몫
CAP, FLOOR = 6_590_000, 410_000

def nps(m, y):
    return int(min(max(m, FLOOR), CAP) * RATE[y])

def gross_deduct(g):  # 소득세법 제47조 근로소득공제(연)
    if g <= 5_000_000: return g * 0.7
    if g <= 15_000_000: return 3_500_000 + (g - 5_000_000) * 0.4
    if g <= 45_000_000: return 7_500_000 + (g - 15_000_000) * 0.15
    if g <= 100_000_000: return 12_000_000 + (g - 45_000_000) * 0.05
    return 14_750_000 + (g - 100_000_000) * 0.02

def bracket(tb):  # 제55조 한계세율
    for lim, r in [(14_000_000, .06), (50_000_000, .15), (88_000_000, .24), (150_000_000, .35)]:
        if tb <= lim: return r
    return .38

for m in [2_000_000, 3_000_000, 4_000_000, 5_000_000, 6_590_000]:
    a, b, c = nps(m, 2026), nps(m, 2027), nps(m, 2033)
    g = m * 12
    # 가정: 본인 1명 기본공제 150만, 4대보험(국민연금 2027·건보 3.595%·장기요양 2026 0.4724%) 공제만, 다른 공제 없음
    hi = m * 0.03595; ltc = m * 0.004724
    tb = g - gross_deduct(g) - 1_500_000 - (b + hi + ltc) * 12
    r = bracket(tb)
    yr = (b - a) * 12
    back = yr * r * 1.1
    print(f"월 {m:>9,} | 2026 {a:>8,} 2027 {b:>8,} (+{b-a:,}/월, +{yr:,}/년) 2033 {c:>8,} (2026 대비 +{c-a:,}/월) | 과세표준≈{tb:,.0f} 세율 {r:.0%} → 돌아옴≈{back:,.0f} 순≈{yr-back:,.0f}")
print('지역가입자 월 200만: 2026', int(2_000_000*.095), '2027', int(2_000_000*.10))
print('7년 누적(300만, 2027~2033 매년 +0.25%p, 2026 대비 더 낸 합):', sum(int(3_000_000*(0.0475+0.0025*k))-142_500 for k in range(1,8))*12)
