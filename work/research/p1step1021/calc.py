A = 3_193_511
def cut(inc, pension):
    e = inc - A
    if e < 2_000_000: c = 0
    elif e < 3_000_000: c = 150_000 + (e-2_000_000)*0.15
    elif e < 4_000_000: c = 300_000 + (e-3_000_000)*0.20
    else: c = 500_000 + (e-4_000_000)*0.25
    return min(c, pension/2), e
def ded(t):
    if t <= 5e6: d = t*.7
    elif t <= 15e6: d = 3.5e6+(t-5e6)*.4
    elif t <= 45e6: d = 7.5e6+(t-15e6)*.15
    elif t <= 100e6: d = 12e6+(t-45e6)*.05
    else: d = 14.75e6+(t-100e6)*.02
    return min(d, 20e6)
print('== 근로소득만, 12개월, 월급(세전, 비과세 제외)별 공제 뒤 월 소득과 감액 (연금 100만원)')
for m in (6_000_000, 6_322_117, 6_500_000, 7_000_000, 8_000_000):
    tot = m*12; inc = (tot-ded(tot))/12
    for p in (1_000_000, 600_000):
        c, e = cut(inc, p)
        print(f'월급 {m:,} 연 {tot:,} 공제 {ded(tot):,.0f} 공제뒤월 {inc:,.0f} 초과 {e:,.0f} 연금 {p:,} 감액 {c:,.0f}')
