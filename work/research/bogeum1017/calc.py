# 보금자리론 원리금균등 월 상환액 (공사 2026-10-01 공시 금리)
import sys; sys.stdout.reconfigure(encoding='utf-8')
def pmt(P, rate, years):
    r = rate/100/12; n = years*12
    return P*r/(1-(1+r)**-n)
P = 300_000_000
cases = [('아낌e 30년', 5.10, 30), ('아낌e 20년', 5.05, 20), ('아낌e 30년 규제지역 +0.2', 5.30, 30),
         ('u 30년', 5.20, 30), ('아낌e 30년 신혼 -0.3', 4.80, 30), ('아낌e 30년 다자녀2 -0.5', 4.60, 30),
         ('은행 신한 최저 4.97 30년', 4.97, 30), ('은행 국민 최저 5.15 30년', 5.15, 30), ('은행 하나 최저 5.30 30년', 5.30, 30)]
for name, rt, y in cases:
    m = pmt(P, rt, y); tot = m*y*12
    print(f'{name}: 월 {m:,.0f}원 · 총이자 {tot-P:,.0f}원')
print('30년 5.10 vs 5.30 월 차이', f'{pmt(P,5.30,30)-pmt(P,5.10,30):,.0f}')
print('30년 vs 20년 월 차이', f'{pmt(P,5.05,20)-pmt(P,5.10,30):,.0f}', '총이자 차이', f'{(pmt(P,5.10,30)*360-P)-(pmt(P,5.05,20)*240-P):,.0f}')
print('중도상환수수료 최대 0.5% of 3억', f'{P*0.005:,.0f}')
print('LTV 70% 6억 =', 6e8*0.7, '한도 3.6억')
