# 2025년 세율(2차): 코스피 0 + 농특세 0.15 · 코스닥 0.15
import sys; sys.stdout.reconfigure(encoding='utf-8')
R26 = {'코스피': 0.0005 + 0.0015, '코스닥': 0.0020, '코넥스': 0.0010}
R25 = {'코스피': 0.0 + 0.0015, '코스닥': 0.0015}
P = 10_000_000  # 원금 1천만원, 팔 때마다 같은 값(1천만원)에 판다고 가정
print('한 번 팔 때:', {k: round(P * v) for k, v in R26.items()}, '2025:', {k: round(P * v) for k, v in R25.items()})
for n, lab in [(1, '1년에 한 번'), (12, '한 달에 한 번'), (52, '일주일에 한 번')]:
    t26 = P * R26['코스피'] * n; t25 = P * R25['코스피'] * n
    print(f'{lab}({n}번 매도): 2026 {t26:,.0f}원 = 원금의 {t26 / P * 100:.1f}% · 2025였다면 {t25:,.0f}원 · 늘어난 몫 {t26 - t25:,.0f}원')
