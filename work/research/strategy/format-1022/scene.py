# 장면 단위로 보기(10/22 format-check) — ytbreak.py의 ask()(제미나이가 유튜브 공개 영상을 말+화면으로 봄)를 그대로 쓰고 질문만 바꾼다.
#   py -3.12 work/research/strategy/format-1022/scene.py <videoId> ...   → scenes/<id>.md (이미 있으면 건너뜀)
# 한 편에 한 번만 묻는다(받아쓰기 따로 안 받음 → 무료 한도 절반). 남의 영상 파일은 받지 않는다.
import sys, os, time
HERE = os.path.dirname(os.path.abspath(__file__)); WORK = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
ids = sys.argv[1:]; sys.argv = sys.argv[:1]          # ytbreak는 import 때 sys.argv의 영상을 돌리므로 비워 둔다
sys.path.insert(0, WORK)
import ytbreak
OUT = os.path.join(HERE, 'scenes'); os.makedirs(OUT, exist_ok=True)
ASK = """이 유튜브 영상을 처음부터 끝까지 말과 화면을 함께 보고, 제작자가 그대로 따라 만들 수 있게 장면 단위로 적어 주세요. 한국어로. 본 것만 쓰고, 모르거나 안 보이면 '모름'이라고 쓰세요. 지어내지 마세요.

## 1. 첫 3초
- 첫 3초 동안 나온 말(그대로 인용):
- 첫 3초 화면에 보인 것(사람·글자·숫자·배경):
- 첫 30초 동안 시청자에게 약속한 것(무엇을 알려 주겠다고 했나, 그대로 인용):

## 2. 장면 표
표 열: 시작~끝(분:초) | 말한 내용 한 줄 | 화면 종류 | 화면에 보인 것 | 숫자를 보여 준 방식
- 화면 종류는 다음 중에서 고르세요(여러 개면 모두): 진행자 얼굴 / 실제 촬영(현장·거리·가게) / 스톡 실사 영상·사진 / AI로 만든 사람 그림·영상 / 만화·일러스트 / 차트(막대·선·원) / 표 / 지도 / 문서·기사·정부 자료 캡처 / 계산 화면(식·영수증·통장) / 자막만 / 기타(무엇인지)
- 장면이 바뀔 때마다 한 줄. 너무 많으면 비슷한 장면은 묶되 30초를 넘겨 묶지 마세요.

## 3. 장(챕터) 순서
번호 | 시작 시각 | 장 이름(영상 속 표기가 있으면 그대로, 없으면 내용) | 그 장의 역할(문제 제기·사례·계산·비교·반전·정리 등)

## 4. 숫자 보여 주는 법
- 큰 숫자가 화면에 처음 나오는 시각과 그 숫자:
- 숫자를 어떤 꼴로 보여 줬나(큰 글자 한 개 / 영수증·내역서처럼 더하고 빼기 / 막대 비교 / 표 / 계산식 / 통장 잔액 / 순위 줄 세우기 등)와 대략 횟수:
- 숫자의 출처를 화면이나 말로 밝혔나(기관 이름 그대로):

## 5. 인물
- 진행자 얼굴이 나오나:
- 사연 속 인물이 있나(이름·나이), 실존 인물인지 가상인지 영상이 밝혔나:
- 목소리: 사람 진행자로 들리나, 합성 음성으로 들리나(확실하지 않으면 '모름'):

## 6. 끝
- 영상 길이:
- 마지막 30초에 한 말(그대로 인용):
- 구독·좋아요·댓글·다음 영상 요청이 있었나, 몇 분 몇 초에, 어떤 말로:
- 댓글로 질문을 던졌나(그대로 인용):

## 7. 화면 종류 비율
영상 전체에서 화면 종류별 대략 비율(%)과, 장면이 평균 몇 초마다 바뀌는지.

## 8. 이 영상이 잘된 이유로 보이는 점 3가지(화면·구성 근거로만)와 약한 점 2가지."""

for vid in ids:
    fn = os.path.join(OUT, vid + '.md')
    if os.path.exists(fn): print('있음', vid); continue
    m, t = ytbreak.ask(vid, ASK, max_out=20000)
    if not t: print('실패(다음 회차로):', vid); continue
    open(fn, 'w', encoding='utf-8').write(f'[{m} · {time.strftime("%Y-%m-%d %H:%M")} · https://www.youtube.com/watch?v={vid}]\n' + t)
    print('저장', vid, m, len(t), flush=True)
    time.sleep(45)
