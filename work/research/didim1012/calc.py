def pmt(P,r,n):
    i=r/100/12
    return P*i/(1-(1+i)**-n)
rows=[("2천만원 이하",{10:2.85,15:2.95,20:3.05,30:3.10}),("2천~4천만원",{10:3.20,15:3.30,20:3.40,30:3.45}),("4천~7천만원",{10:3.55,15:3.65,20:3.75,30:3.85}),("7천~8.5천만원",{10:3.90,15:4.00,20:4.10,30:4.15})]
for P in (20000,24000,32000):
  for lab,d in rows:
    for y in (30,):
        m=pmt(P*10000,d[y],y*12)
        print(P,lab,y,d[y],round(m),'총이자',round(m*y*12-P*10000))
